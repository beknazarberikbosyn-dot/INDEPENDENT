#!/usr/bin/env python3
"""Pre-record the assistant's phrases with ElevenLabs and write voice/manifest.js.

The API key is NEVER stored in the site: clips are generated once and committed as mp3 files.
Usage:
  ELEVENLABS_API_KEY=... python3 tools/gen_voice.py tools/phrases.json [--dry-run]
Clips that already exist are reused, so re-running only pays for new phrases.
"""
import hashlib, json, os, re, sys, time, urllib.request, urllib.error

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VOICE_ID = "EXAVITQu4vr4xnSDxMaL"          # "Sarah" — warm, calm, mature female voice
MODEL_ID = "eleven_v4_turbo"               # supports Kazakh and Russian, 0.5 credit / character
FORMAT = "mp3_44100_64"
SETTINGS = {"stability": 0.6, "similarity_boost": 0.8, "style": 0.15, "use_speaker_boost": True, "speed": 0.92}


def key(lang, text):
    return lang + "|" + re.sub(r"\s+", " ", text.strip()).lower()


def fname(lang, text):
    h = hashlib.sha1(key(lang, text).encode("utf-8")).hexdigest()[:12]
    return f"voice/{lang}/{h}.mp3"


def spoken(lang, text):
    """Text sent to TTS: small fixes so the voice reads numbers and symbols naturally."""
    t = text.replace("—", ",").replace("«", "").replace("»", "")
    t = t.replace("₸", " тенге" if lang == "ru" else " теңге")
    return re.sub(r"\s+", " ", t).strip()


def tts(lang, text):
    body = json.dumps({"text": spoken(lang, text), "model_id": MODEL_ID, "language_code": lang,
                       "voice_settings": SETTINGS, "apply_text_normalization": "on"}).encode()
    req = urllib.request.Request(
        f"https://api.elevenlabs.io/v1/text-to-speech/{VOICE_ID}?output_format={FORMAT}", data=body,
        headers={"Content-Type": "application/json", "xi-api-key": os.environ.get("ELEVENLABS_API_KEY", "proxy-injected")})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tools", "phrases.json")
    dry = "--dry-run" in sys.argv
    phrases = json.load(open(src, encoding="utf-8"))
    todo = [p for p in phrases if not os.path.exists(os.path.join(ROOT, fname(p["lang"], p["text"])))]
    cost = sum(len(spoken(p["lang"], p["text"])) for p in todo) * 0.5
    print(f"{len(phrases)} phrases, {len(todo)} new, ~{cost:.0f} credits")
    if dry:
        return
    for i, p in enumerate(todo, 1):
        out = os.path.join(ROOT, fname(p["lang"], p["text"]))
        os.makedirs(os.path.dirname(out), exist_ok=True)
        for attempt in range(3):
            try:
                data = tts(p["lang"], p["text"])
                break
            except urllib.error.HTTPError as e:
                print("HTTP", e.code, e.read()[:200], file=sys.stderr)
                if e.code in (401, 402, 403):
                    sys.exit(1)
                time.sleep(2 + attempt * 3)
        else:
            print("failed:", p["text"], file=sys.stderr)
            continue
        open(out, "wb").write(data)
        print(f"[{i}/{len(todo)}] {p['lang']} {p['text'][:60]}")
    manifest = {key(p["lang"], p["text"]): fname(p["lang"], p["text"]) for p in phrases
                if os.path.exists(os.path.join(ROOT, fname(p["lang"], p["text"])))}
    with open(os.path.join(ROOT, "voice", "manifest.js"), "w", encoding="utf-8") as f:
        f.write("/* Pre-recorded assistant phrases (ElevenLabs, voice \"Sarah\", eleven_v4_turbo). Generated by tools/gen_voice.py */\n")
        f.write("window.VOICE_CLIPS = " + json.dumps(manifest, ensure_ascii=False, indent=0) + ";\n")
    print("manifest:", len(manifest), "clips")


if __name__ == "__main__":
    main()
